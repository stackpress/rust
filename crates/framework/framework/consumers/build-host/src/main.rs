//! App-owned finite generation: actual aggregate helpers and schema/SQL/admin emitters.
use stackpress_framework::commands::schema::rust::{self, transformer::*};
use stackpress_framework_schema::{FieldAccess, Schema, codegen::*};
use std::path::Path;

/// Approve only this application's two public fields and the real admin component catalog.
fn definitions() -> stackpress_framework_schema::SchemaResult<DefinitionRegistry> {
    let mut definitions = DefinitionRegistry::standard();
    for field in ["id", "title"] {
        definitions = definitions.with_field_policy(
            "Note",
            field,
            FieldAccess {
                readable: true,
                writable: true,
                sensitive: false,
                publish_default: false,
            },
        )?;
    }
    stackpress_framework_admin::codegen::register_components(definitions, Vec::new())
}

/// Every partition normalizes the same application schema and frozen definition registry.
fn normalized(context: &TransformContext<'_>) -> Result<(Schema, DefinitionRegistry)> {
    let definitions = definitions().map_err(transform_error)?;
    let schema = Schema::normalize(context.schema(), &definitions, NormalizeOptions::default())
        .map_err(transform_error)?;
    Ok((schema, definitions))
}

/// Contracts are generated by the existing schema emitter, never handwritten fixtures.
fn schema(context: &TransformContext<'_>, output: &mut OutputPlan) -> Result<()> {
    emit_contracts(&normalized(context)?.0, output)
}

/// Include actual generated SQL operations consumed by the generated admin registrar.
fn sql(context: &TransformContext<'_>, output: &mut OutputPlan) -> Result<()> {
    stackpress_framework_sql::codegen::emit_stores_with_diagnostics(
        &normalized(context)?.0,
        output,
        &DiagnosticMap {
            entries: Vec::new(),
        },
        true,
    )
}

/// Roles, typed pages and pages_host are emitted together from the same schema.
fn admin(context: &TransformContext<'_>, output: &mut OutputPlan) -> Result<()> {
    let (schema, definitions) = normalized(context)?;
    stackpress_framework_admin::codegen::emit_roles(
        &schema.project_ui().map_err(transform_error)?,
        &definitions,
        &DiagnosticMap {
            entries: Vec::new(),
        },
        output,
    )?;
    stackpress_framework_admin::codegen::emit_pages(&schema, &definitions, &["Note"], output)
}

/// The writer assembles partition modules; this app adds no replacement source strings.
fn root(_: &rust::parser::SchemaConfig) -> Result<Vec<GeneratedFile>> {
    Ok(Vec::new())
}

/// Explicit generation/check operation, with no runtime consumer or process listener.
fn main() -> std::result::Result<(), Box<dyn std::error::Error>> {
    let base = Path::new(env!("CARGO_MANIFEST_DIR"));
    let mut registry = Registry::new();
    rust::register(&mut registry, schema, Some(sql), None)?;
    stackpress_framework_admin::codegen::register_pages(&mut registry, admin)?;
    let mode = if std::env::args().any(|arg| arg == "--check") {
        rust::GenerationMode::Check
    } else {
        rust::GenerationMode::Install
    };
    let report = rust::generate(
        rust::GenerateRequest::new("schema.idea", root, mode),
        ProjectLoader::new(base)?,
        &registry,
        &OutputWorkspace::new(base.parent().expect("consumer parent").join("generated"))?,
    )?;
    if mode == rust::GenerationMode::Check {
        assert!(report.is_current());
    }
    println!("slice11 build-host consumer passed");
    Ok(())
}
