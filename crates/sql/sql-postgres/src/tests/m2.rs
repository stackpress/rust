//! Opt-in native M2 proofs: parent owns CREATE/DROP, child owns all hang-class scenarios.
//! Unset gate variables are reported as ignored; child timeout is always failure.

use crate::{PostgresDatabase, PostgresOptions, PostgresTls};
use sqlx::postgres::{PgConnectOptions, PgConnection, PgSslMode};
use sqlx::{ConnectOptions, Connection, Executor, SqlSafeStr};
use stackpress_sql::{Database, DialectId, Query, QueryLimits, Render, Sql, SqlValue};
use std::process::{Child, Command, ExitStatus};
use std::str::FromStr;
use std::sync::atomic::{AtomicBool, Ordering};
use std::time::{Duration, Instant, SystemTime, UNIX_EPOCH};

/// Concrete private owner used by the shared stress implementation.
type TestDatabase = PostgresDatabase;

/// Test errors are never formatted: native setup diagnostics may contain connection data.
type TestResult<T> = Result<T, Box<dyn std::error::Error + Send + Sync>>;
/// Unwind cleanup must not turn a failing cleanup into a green process exit.
static CLEANUP_FAILED: AtomicBool = AtomicBool::new(false);
/// Preserve the established environment gate without reading credentials into logs.
const GATE: &str = "STACKPRESS_TEST_POSTGRES_URL";
/// Fixed backend identity: the fixture never infers it from untrusted URL text.
const DIALECT: DialectId = DialectId::Postgres;

/// Only the successful CREATE path can arm this cleanup authority.
struct Fixture {
    /// Generated bounded ASCII identifier, never copied from an environment URL.
    name: String,
    /// True only after this process's CREATE acknowledged success.
    armed: bool,
}
impl Fixture {
    /// Create exactly one unique database, never adopt a pre-existing name.
    fn create() -> TestResult<Self> {
        let name = format!(
            "stackpress_s7_m2_{:x}_{:x}",
            std::process::id(),
            SystemTime::now().duration_since(UNIX_EPOCH)?.as_nanos()
        );
        validate_name(&name)?;
        println!("attempting CREATE of exact database {name}");
        let create_name = name.clone();
        bounded_admin(move |connection| {
            Box::pin(async move {
                let sql = format!("CREATE DATABASE {}", quoted(&create_name));
                connection
                    .execute(sqlx::AssertSqlSafe(sql).into_sql_str())
                    .await?;
                Ok(())
            })
        })?;
        // Arm only after CREATE succeeds; failure before this point never runs DROP.
        println!("created owned database {name}");
        Ok(Self { name, armed: true })
    }
    /// Close-owning child has exited/reaped before this independent cleanup deadline starts.
    fn cleanup(&mut self) -> TestResult<()> {
        if !self.armed {
            return Ok(());
        }
        let name = self.name.clone();
        let result = bounded_admin(move |connection| {
            Box::pin(async move {
                // PostgreSQL 12 has no FORCE. A just-disposed own socket may still finish
                // its current statement; retry only DROP of this armed database, no catalogs.
                loop {
                    let sql = format!("DROP DATABASE {}", quoted(&name));
                    match connection
                        .execute(sqlx::AssertSqlSafe(sql).into_sql_str())
                        .await
                    {
                        Ok(_) => break,
                        Err(error) if own_sessions_finishing(&error) => {
                            tokio::time::sleep(Duration::from_millis(25)).await
                        }
                        Err(error) => return Err(error.into()),
                    }
                }
                Ok(())
            })
        });
        if result.is_ok() {
            self.armed = false;
            println!("drop confirmed: {}", self.name);
        } else {
            eprintln!("cleanup FAILED for exact owned database {}", self.name);
        }
        result
    }
}
impl Drop for Fixture {
    /// Attempt exact-name cleanup on failure/unwind; failure affects the process result.
    fn drop(&mut self) {
        if self.armed && self.cleanup().is_err() {
            CLEANUP_FAILED.store(true, Ordering::SeqCst);
        }
    }
}
/// Accept only names generated by this harness; SQL quoting never accepts URL database text.
fn validate_name(name: &str) -> TestResult<()> {
    if !(20..=63).contains(&name.len())
        || !name.starts_with("stackpress_s7_m2_")
        || !name
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'_')
    {
        return Err("invalid owned fixture identifier".into());
    }
    Ok(())
}
/// Quote the already-validated generated identifier for this backend only.
fn quoted(name: &str) -> String {
    format!("\"{name}\"")
}
/// Only PostgreSQL's structured object-in-use code permits an exact-owned DROP retry.
fn own_sessions_finishing(error: &sqlx::Error) -> bool {
    matches!(error, sqlx::Error::Database(native) if native.code().as_deref() == Some("55006"))
}
/// Parse the opt-in local URL without printing it or permitting another server/identity.
fn fixture_options() -> TestResult<PgConnectOptions> {
    let source = std::env::var(GATE)?;
    let parsed = PgConnectOptions::from_str(&source)?;
    if !matches!(parsed.get_host(), "localhost" | "127.0.0.1")
        || parsed.get_port() != 5432
        || parsed.get_username() != "postgres"
    {
        return Err("fixture URL must select the authorized local development server".into());
    }
    // Preserve URL compatibility in tests only; production options never accept a URL.
    Ok(parsed
        .ssl_mode(PgSslMode::Disable)
        .disable_statement_logging())
}
/// Execute administration on a separate runtime with both an IO and wall-clock deadline.
fn bounded_admin(
    operation: impl for<'a> FnOnce(
        &'a mut PgConnection,
    ) -> std::pin::Pin<
        Box<dyn std::future::Future<Output = TestResult<()>> + Send + 'a>,
    > + Send
    + 'static,
) -> TestResult<()> {
    let (sender, receiver) = std::sync::mpsc::sync_channel(1);
    let worker = std::thread::spawn(move || {
        let result = (|| -> TestResult<()> {
            let runtime = tokio::runtime::Builder::new_current_thread()
                .enable_all()
                .build()?;
            runtime.block_on(async {
                tokio::time::timeout(Duration::from_secs(9), async {
                    let mut connection = PgConnection::connect_with(&fixture_options()?).await?;
                    let result = operation(&mut connection).await;
                    // Close this administrative socket before publishing the result.
                    let close = connection.close().await;
                    result?;
                    close?;
                    Ok(())
                })
                .await?
            })
        })();
        let _ = sender.send(result);
    });
    // A synchronous/CPU hang in the worker cannot keep the harness alive forever.
    let result = receiver
        .recv_timeout(Duration::from_secs(10))
        .map_err(|_| "administration wall-clock deadline exceeded")?;
    worker
        .join()
        .map_err(|_| "administration worker panicked")?;
    result
}
/// Wait without trusting an in-runtime timeout; timeout always kills and reaps the child.
fn watchdog(mut child: Child, deadline: Duration) -> TestResult<ExitStatus> {
    let start = Instant::now();
    loop {
        match child.try_wait() {
            Ok(Some(status)) => return Ok(status),
            Ok(None) => {}
            Err(error) => {
                // Even observation failures must not leave a native scenario running.
                let _ = child.kill();
                let _ = child.wait();
                return Err(error.into());
            }
        }
        if start.elapsed() >= deadline {
            let _ = child.kill();
            let _ = child.wait();
            return Err(
                "native scenario process watchdog timed out; child killed and reaped".into(),
            );
        }
        std::thread::sleep(Duration::from_millis(10));
    }
}
/// Print only sanitized first-party context and structured native categories.
fn report_error(error: &(dyn std::error::Error + 'static)) {
    // Walk a bounded cause chain, formatting only safe first-party contexts and typed codes.
    let mut current = Some(error);
    for _ in 0..8 {
        let Some(error) = current else { break };
        if let Some(error) = error.downcast_ref::<stackpress_framework_sql::DataError>() {
            eprintln!("data failure category {:?}: {error}", error.kind());
        }
        if let Some(error) = error.downcast_ref::<stackpress_sql::SqlError>() {
            eprintln!("SQL failure category {:?}: {error}", error.kind());
        }
        if let Some(native) = error.downcast_ref::<sqlx::Error>() {
            match native {
                sqlx::Error::Database(database) => {
                    eprintln!("native structured code: {:?}", database.code())
                }
                sqlx::Error::Io(io) => eprintln!("native IO category: {:?}", io.kind()),
                sqlx::Error::ColumnDecode { .. } | sqlx::Error::Decode(_) => {
                    eprintln!("native decode failure")
                }
                _ => eprintln!("native failure (detail redacted)"),
            }
        }
        current = error.source();
    }
}

