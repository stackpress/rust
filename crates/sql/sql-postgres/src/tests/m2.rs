/// Build a detached statement using the unchanged core trust/lexical contract.
fn query(sql: &'static str, values: impl IntoIterator<Item = SqlValue>) -> Query {
    let mut builder = Sql::literal(DIALECT, sql);
    for value in values {
        builder = builder.bind(value);
    }
    builder.render(DIALECT).unwrap()
}
/// Open exactly the armed database with scenario-owned finite limits.
async fn open_config(name: &str, config: stress::Config) -> TestResult<PostgresDatabase> {
    validate_name(name)?;
    let native = fixture_options()?;
    let mut options = PostgresOptions::new(native.get_host(), name, native.get_username(), "");
    options.port = native.get_port();
    options.tls = PostgresTls::Plaintext;
    options.max_connections = config.max;
    options.max_in_flight = config.admission;
    options.acquire_timeout_ms = config.acquire_ms;
    options.statement_timeout_ms = 2000;
    options.cleanup_timeout_ms = 500;
    Ok(PostgresDatabase::open(options).await?)
}
/// Run a statement and preserve sanitized first-party error context on failure.
async fn run(
    database: &PostgresDatabase,
    sql: &'static str,
    binds: impl IntoIterator<Item = SqlValue>,
) -> TestResult<stackpress_sql::QueryResult> {
    Ok(database
        .run(query(sql, binds), QueryLimits::default())
        .await?)
}
/// Read one strict integer; the SQL itself is constant fixture source.
async fn integer(database: &PostgresDatabase, sql: &'static str) -> TestResult<i64> {
    Ok(run(database, sql, []).await?.rows[0].try_get_at(0)?)
}
/// Run every group in an independently killable process while the parent keeps DROP authority.
pub(crate) fn main() {
    if std::env::args().nth(1).as_deref() == Some("--m2-sqlite") {
        let result = std::panic::catch_unwind(|| -> TestResult<()> {
            let path = std::env::args_os()
                .nth(2)
                .ok_or("missing SQLite reference path")?;
            let runtime = tokio::runtime::Builder::new_multi_thread()
                .worker_threads(2)
                .enable_all()
                .build()?;
            runtime.block_on(sqlite::child(path.into()))
        });
        if let Ok(Err(error)) = &result {
            report_error(error.as_ref());
        }
        if !matches!(result, Ok(Ok(()))) {
            eprintln!("SQLite reference failed");
            std::process::exit(1);
        }
        return;
    }
    if std::env::args().nth(1).as_deref() == Some("--m2-scenario") {
        let result = std::panic::catch_unwind(|| -> TestResult<()> {
            let name = std::env::args().nth(2).ok_or("missing owned database")?;
            let case = std::env::args().nth(3).ok_or("missing scenario group")?;
            let runtime = tokio::runtime::Builder::new_multi_thread()
                .worker_threads(2)
                .enable_all()
                .build()?;
            runtime.block_on(async {
                match case.as_str() {
                    "contract" => {
                        let database = open_config(&name, stress::Config::contract()).await?;
                        contract::run_suite(std::sync::Arc::new(database)).await?;
                        Ok(())
                    }
                    "stress" => stress::run(&name).await,
                    _ => Err("unknown M2 scenario".into()),
                }
            })
        });
        if let Ok(Err(error)) = &result {
            report_error(error.as_ref());
        }
        if !matches!(result, Ok(Ok(()))) {
            eprintln!("M2 scenario failed; native diagnostics redacted");
            std::process::exit(1);
        }
        return;
    }
    // SQLite is an offline reference, independently owned/reaped before network fixtures.
    if let Err(error) = sqlite::parent() {
        report_error(error.as_ref());
        std::process::exit(1);
    }
    println!("test m2::sqlite_reference ... ok");
    if std::env::var_os(GATE).is_none() {
        println!("test m2::native_cases ... ignored ({GATE} unset)");
        println!("test result: ok. 1 passed; 0 failed; 2 ignored");
        return;
    }
    let result = std::panic::catch_unwind(|| -> TestResult<()> {
        let mut fixture = Fixture::create()?;
        let start = Instant::now();
        let mut primary: TestResult<()> = Ok(());
        for case in ["contract", "stress"] {
            let remaining = Duration::from_secs(120).saturating_sub(start.elapsed());
            let case_start = Instant::now();
            let status = watchdog(
                Command::new(std::env::current_exe()?)
                    .arg("--m2-scenario")
                    .arg(&fixture.name)
                    .arg(case)
                    .spawn()?,
                remaining.min(Duration::from_secs(30)),
            );
            println!("M2 {case} child wall time {:?}", case_start.elapsed());
            match status {
                Ok(status) if status.success() => println!("test m2::{case} ... ok"),
                _ => {
                    primary = Err("M2 native child failed or timed out".into());
                    // Independent groups still run; the fixture remains failing.
                }
            }
        }
        let cleanup = fixture.cleanup();
        primary?;
        cleanup
    });
    if let Ok(Err(error)) = &result {
        report_error(error.as_ref());
    }
    if !matches!(result, Ok(Ok(()))) || CLEANUP_FAILED.load(Ordering::SeqCst) {
        eprintln!("test result: FAILED (M2 setup/scenario/cleanup)");
        std::process::exit(1);
    }
    println!("test result: ok. 3 M2 groups passed; 0 ignored");
}
