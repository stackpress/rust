//! Opt-in native M0 proofs: parent owns CREATE/DROP, child owns all hang-class scenarios.
//! Unset gate variables are reported as ignored; child timeout is always failure.

use sqlx::mysql::{MySqlConnectOptions, MySqlConnection, MySqlSslMode};
use sqlx::{ConnectOptions, Connection, Executor, SqlSafeStr};
use stackpress_sql::{
    Database, DialectId, ErrorKind, Query, QueryLimits, Render, Sql, SqlValue, TransactionOptions,
};
use stackpress_sql_mysql::{MysqlDatabase, MysqlOptions, MysqlTls};
use std::process::{Child, Command, ExitStatus};
use std::str::FromStr;
use std::sync::atomic::{AtomicBool, Ordering};
use std::time::{Duration, Instant, SystemTime, UNIX_EPOCH};

/// Test errors are never formatted: native setup diagnostics may contain connection data.
type TestResult<T> = Result<T, Box<dyn std::error::Error + Send + Sync>>;
/// Unwind cleanup must not turn a failing cleanup into a green process exit.
static CLEANUP_FAILED: AtomicBool = AtomicBool::new(false);
/// Preserve the established environment gate without reading credentials into logs.
const GATE: &str = "STACKPRESS_TEST_MYSQL_URL";
/// Fixed backend identity: the fixture never infers it from untrusted URL text.
const DIALECT: DialectId = DialectId::Mysql;

/// Only the successful CREATE path can arm this cleanup authority.
struct Fixture {
    /// Generated bounded ASCII identifier, never copied from an environment URL.
    name: String,
    /// True only after this process's CREATE acknowledged success.
    armed: bool,
}
impl Fixture {
    /// Create exactly one unique database, never adopt a pre-existing name.
    fn create() -> TestResult<Self> {
        let name = format!(
            "stackpress_s7_m0_{:x}_{:x}",
            std::process::id(),
            SystemTime::now().duration_since(UNIX_EPOCH)?.as_nanos()
        );
        validate_name(&name)?;
        println!("attempting CREATE of exact database {name}");
        let create_name = name.clone();
        bounded_admin(move |connection| {
            Box::pin(async move {
                let sql = format!("CREATE DATABASE {}", quoted(&create_name));
                connection
                    .execute(sqlx::AssertSqlSafe(sql).into_sql_str())
                    .await?;
                Ok(())
            })
        })?;
        // Arm only after CREATE succeeds; failure before this point never runs DROP.
        println!("created owned database {name}");
        Ok(Self { name, armed: true })
    }
    /// Close-owning child has exited/reaped before this independent cleanup deadline starts.
    fn cleanup(&mut self) -> TestResult<()> {
        if !self.armed {
            return Ok(());
        }
        let name = self.name.clone();
        let result = bounded_admin(move |connection| {
            Box::pin(async move {
                // PostgreSQL 12 has no FORCE. A just-disposed own socket may still finish
                // its current statement; retry only DROP of this armed database, no catalogs.
                loop {
                    let sql = format!("DROP DATABASE {}", quoted(&name));
                    match connection
                        .execute(sqlx::AssertSqlSafe(sql).into_sql_str())
                        .await
                    {
                        Ok(_) => break,
                        Err(error) if own_sessions_finishing(&error) => {
                            tokio::time::sleep(Duration::from_millis(25)).await
                        }
                        Err(error) => return Err(error.into()),
                    }
                }
                Ok(())
            })
        });
        if result.is_ok() {
            self.armed = false;
            println!("drop confirmed: {}", self.name);
        } else {
            eprintln!("cleanup FAILED for exact owned database {}", self.name);
        }
        result
    }
}
impl Drop for Fixture {
    /// Attempt exact-name cleanup on failure/unwind; failure affects the process result.
    fn drop(&mut self) {
        if self.armed && self.cleanup().is_err() {
            CLEANUP_FAILED.store(true, Ordering::SeqCst);
        }
    }
}
/// Accept only names generated by this harness; SQL quoting never accepts URL database text.
fn validate_name(name: &str) -> TestResult<()> {
    if !(20..=63).contains(&name.len())
        || !name.starts_with("stackpress_s7_m0_")
        || !name
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'_')
    {
        return Err("invalid owned fixture identifier".into());
    }
    Ok(())
}
/// Quote the already-validated generated identifier for this backend only.
fn quoted(name: &str) -> String {
    format!("`{name}`")
}
/// Only PostgreSQL's structured object-in-use code permits an exact-owned DROP retry.
fn own_sessions_finishing(error: &sqlx::Error) -> bool {
    {
        let _ = error;
        false
    }
}
/// Parse the opt-in local URL without printing it or permitting another server/identity.
fn fixture_options() -> TestResult<MySqlConnectOptions> {
    let source = std::env::var(GATE)?;
    let parsed = MySqlConnectOptions::from_str(&source)?;
    if !matches!(parsed.get_host(), "localhost" | "127.0.0.1")
        || parsed.get_port() != 3306
        || parsed.get_username() != "root"
    {
        return Err("fixture URL must select the authorized local development server".into());
    }
    // Preserve URL compatibility in tests only; production options never accept a URL.
    Ok(parsed
        .ssl_mode(MySqlSslMode::Disabled)
        .disable_statement_logging())
}
/// Execute administration on a separate runtime with both an IO and wall-clock deadline.
fn bounded_admin(
    operation: impl for<'a> FnOnce(
        &'a mut MySqlConnection,
    ) -> std::pin::Pin<
        Box<dyn std::future::Future<Output = TestResult<()>> + Send + 'a>,
    > + Send
    + 'static,
) -> TestResult<()> {
    let (sender, receiver) = std::sync::mpsc::sync_channel(1);
    let worker = std::thread::spawn(move || {
        let result = (|| -> TestResult<()> {
            let runtime = tokio::runtime::Builder::new_current_thread()
                .enable_all()
                .build()?;
            runtime.block_on(async {
                tokio::time::timeout(Duration::from_secs(9), async {
                    let mut connection = MySqlConnection::connect_with(&fixture_options()?).await?;
                    let result = operation(&mut connection).await;
                    // Close this administrative socket before publishing the result.
                    let close = connection.close().await;
                    result?;
                    close?;
                    Ok(())
                })
                .await?
            })
        })();
        let _ = sender.send(result);
    });
    // A synchronous/CPU hang in the worker cannot keep the harness alive forever.
    let result = receiver
        .recv_timeout(Duration::from_secs(10))
        .map_err(|_| "administration wall-clock deadline exceeded")?;
    worker
        .join()
        .map_err(|_| "administration worker panicked")?;
    result
}
/// Build a detached trusted statement with data kept in native binds.
fn query(sql: &'static str, values: impl IntoIterator<Item = SqlValue>) -> Query {
    let mut builder = Sql::literal(DIALECT, sql);
    for value in values {
        builder = builder.bind(value);
    }
    builder.render(DIALECT).unwrap()
}
/// Assert one native integer cell without exposing source SQL in error messages.
async fn integer(database: &MysqlDatabase, sql: &'static str) -> i64 {
    database
        .run(query(sql, []), QueryLimits::default())
        .await
        .unwrap()
        .rows[0]
        .try_get_at(0)
        .unwrap()
}
/// Exercise every M0 lifecycle seam inside the parent-owned process watchdog.
async fn scenario(name: &str) -> TestResult<Box<dyn stackpress_sql::TransactionSession>> {
    validate_name(name)?;
    let native = fixture_options()?;
    let mut options = MysqlOptions::new(native.get_host(), name, native.get_username(), "");
    options.port = native.get_port();
    options.tls = MysqlTls::Plaintext;
    options.max_connections = 1;
    options.max_in_flight = 4;
    options.acquire_timeout_ms = 100;
    options.statement_timeout_ms = 2000;
    options.cleanup_timeout_ms = 1000;
    let database = MysqlDatabase::open(options).await?;
    let version = database
        .run(query("SELECT version()", []), QueryLimits::default())
        .await?
        .rows[0]
        .try_get_at::<String>(0)?;
    println!("owned fixture server version: {version}");
    println!("M0 owner opened; beginning typed round trip");
    // Typed parameters and a native typed NULL share the real prepared/executing lease.
    let row = database.run(query("SELECT CAST(? AS SIGNED) AS value, CAST(? AS CHAR) AS text, CAST(? AS BINARY) AS bytes, CAST(? AS SIGNED) AS flag, (? + 0e0) AS real_value, CAST(? AS SIGNED) AS missing",
        [SqlValue::Integer(42), SqlValue::Text("O'Reilly ☃".into()), SqlValue::Blob(vec![0,255,1]), SqlValue::Bool(true), SqlValue::Real(1.5), SqlValue::Null]), QueryLimits::default()).await?.rows.remove(0);
    assert_eq!(row.try_get_at::<i64>(0)?, 42);
    assert_eq!(row.try_get_at::<String>(1)?, "O'Reilly ☃");
    assert_eq!(row.cells()[2].1, SqlValue::Blob(vec![0, 255, 1]));
    assert!(row.try_get_at::<bool>(3)?);
    assert_eq!(row.cells()[4].1, SqlValue::Real(1.5));
    assert_eq!(row.cells()[5].1, SqlValue::Null);
    println!("test m0::typed_and_null_round_trip ... ok");

    database
        .run(
            query(
                "CREATE TABLE m0_items (id BIGINT PRIMARY KEY, value BIGINT) ENGINE=InnoDB",
                [],
            ),
            QueryLimits::default(),
        )
        .await?;
    let mut transaction = database.begin(TransactionOptions::default()).await?;
    transaction
        .run(
            query("INSERT INTO m0_items VALUES (1, 10)", []),
            QueryLimits::default(),
        )
        .await?;
    assert_eq!(
        transaction
            .run(
                query("SELECT value FROM m0_items WHERE id = 1", []),
                QueryLimits::default()
            )
            .await?
            .rows[0]
            .try_get_at::<i64>(0)?,
        10
    );
    // A nested database operation cannot steal the transaction's one native connection.
    let nested = database
        .run(
            query("SELECT value FROM m0_items", []),
            QueryLimits::default(),
        )
        .await;
    assert_eq!(nested.unwrap_err().kind(), ErrorKind::PoolTimedOut);
    transaction.commit().await?;
    assert_eq!(
        integer(&database, "SELECT value FROM m0_items WHERE id = 1").await,
        10
    );
    println!("test m0::exclusive_transaction ... ok");

    // Poll into real native execution, cancel, then demand a clean fresh lease.
    let before = integer(&database, "SELECT CONNECTION_ID()").await;
    assert!(
        tokio::time::timeout(
            Duration::from_millis(50),
            database.run(
                query("SELECT CAST(SLEEP(0.3) AS SIGNED)", []),
                QueryLimits::default()
            )
        )
        .await
        .is_err()
    );
    let after = integer(&database, "SELECT CONNECTION_ID()").await;
    assert_ne!(before, after);
    let mut transaction = database.begin(TransactionOptions::default()).await?;
    transaction
        .run(
            query("INSERT INTO m0_items VALUES (2, 20)", []),
            QueryLimits::default(),
        )
        .await?;
    assert!(
        tokio::time::timeout(
            Duration::from_millis(50),
            transaction.run(
                query("SELECT CAST(SLEEP(0.3) AS SIGNED)", []),
                QueryLimits::default()
            )
        )
        .await
        .is_err()
    );
    assert_eq!(
        transaction
            .run(
                query("SELECT value FROM m0_items", []),
                QueryLimits::default()
            )
            .await
            .unwrap_err()
            .kind(),
        ErrorKind::RollbackOnly
    );
    transaction.rollback().await?;
    assert_eq!(
        integer(&database, "SELECT COUNT(*) FROM m0_items WHERE id = 2").await,
        0
    );
    println!("test m0::cancelled_lease_clean_fresh_session ... ok");

    // A consuming future owns its lease even when dropped before its first poll.
    let mut transaction = database.begin(TransactionOptions::default()).await?;
    transaction
        .run(
            query("INSERT INTO m0_items VALUES (3, 30)", []),
            QueryLimits::default(),
        )
        .await?;
    drop(transaction.commit());
    assert_eq!(
        integer(&database, "SELECT COUNT(*) FROM m0_items WHERE id = 3").await,
        0
    );
    println!("test m0::unpolled_commit_retires ... ok");

    let transaction = database.begin(TransactionOptions::default()).await?;
    assert!(
        tokio::time::timeout(Duration::from_millis(25), database.close())
            .await
            .is_err()
    );
    assert_eq!(
        database
            .run(
                query("SELECT value FROM m0_items", []),
                QueryLimits::default()
            )
            .await
            .unwrap_err()
            .kind(),
        ErrorKind::Closed
    );
    transaction.rollback().await?;
    database.close().await?;
    database.close().await?;
    println!("test m0::cancelled_close_reawaits ... ok");

    // Return a real held session so main can Drop it outside an entered Tokio runtime.
    let native = fixture_options()?;
    let mut options = MysqlOptions::new(native.get_host(), name, native.get_username(), "");
    options.tls = MysqlTls::Plaintext;
    options.max_connections = 1;
    let outside = MysqlDatabase::open(options).await?;
    let mut transaction = outside.begin(TransactionOptions::default()).await?;
    transaction
        .run(
            query("INSERT INTO m0_items VALUES (4, 40)", []),
            QueryLimits::default(),
        )
        .await?;
    // Database owner can go away first; the session still owns the native pool lease.
    drop(outside);
    Ok(transaction)
}
/// Wait without trusting an in-runtime timeout; timeout always kills and reaps the child.
fn watchdog(mut child: Child, deadline: Duration) -> TestResult<ExitStatus> {
    let start = Instant::now();
    loop {
        match child.try_wait() {
            Ok(Some(status)) => return Ok(status),
            Ok(None) => {}
            Err(error) => {
                // Even observation failures must not leave a native scenario running.
                let _ = child.kill();
                let _ = child.wait();
                return Err(error.into());
            }
        }
        if start.elapsed() >= deadline {
            let _ = child.kill();
            let _ = child.wait();
            return Err(
                "native scenario process watchdog timed out; child killed and reaped".into(),
            );
        }
        std::thread::sleep(Duration::from_millis(10));
    }
}
/// Print only sanitized first-party context and structured native categories.
fn report_error(error: &(dyn std::error::Error + 'static)) {
    if let Some(error) = error.downcast_ref::<stackpress_sql::SqlError>() {
        eprintln!("SQL failure category {:?}: {error}", error.kind());
    }
    let native = error.downcast_ref::<sqlx::Error>().or_else(|| {
        error
            .source()
            .and_then(|source| source.downcast_ref::<sqlx::Error>())
    });
    if let Some(native) = native {
        match native {
            sqlx::Error::Database(database) => {
                eprintln!("native structured code: {:?}", database.code())
            }
            sqlx::Error::Io(io) => eprintln!("native IO category: {:?}", io.kind()),
            sqlx::Error::ColumnDecode { .. } | sqlx::Error::Decode(_) => {
                eprintln!("native decode failure")
            }
            _ => eprintln!("native failure (detail redacted)"),
        }
    }
}
/// Report skips explicitly and keep fixture authority in the parent through child failure.
fn main() {
    if std::env::args().nth(1).as_deref() == Some("--scenario") {
        let result = std::panic::catch_unwind(|| -> TestResult<()> {
            let name = std::env::args().nth(2).ok_or("missing owned database")?;
            let runtime = tokio::runtime::Builder::new_multi_thread()
                .worker_threads(2)
                .enable_all()
                .build()?;
            let session = runtime.block_on(scenario(&name))?;
            // No runtime is entered here. Raw socket RAII must not panic or recycle.
            drop(runtime);
            drop(session);
            // Reopen with a new runtime and a fresh native lease to verify the abandoned
            // transaction left no row. This proves local socket disposal, not immediate
            // remote acknowledgement for arbitrary workloads.
            let runtime = tokio::runtime::Builder::new_current_thread()
                .enable_all()
                .build()?;
            runtime.block_on(async {
                let native = fixture_options()?;
                let mut options =
                    MysqlOptions::new(native.get_host(), &name, native.get_username(), "");
                options.tls = MysqlTls::Plaintext;
                let fresh = MysqlDatabase::open(options).await?;
                assert_eq!(
                    integer(&fresh, "SELECT COUNT(*) FROM m0_items WHERE id = 4").await,
                    0
                );
                fresh.close().await?;
                Ok::<(), Box<dyn std::error::Error + Send + Sync>>(())
            })?;
            println!("test m0::outside_runtime_drop ... ok");
            Ok(())
        });
        if let Ok(Err(error)) = &result {
            report_error(error.as_ref());
        }
        if !matches!(result, Ok(Ok(()))) {
            eprintln!("M0 scenario failed (native diagnostics redacted)");
            std::process::exit(1);
        }
        return;
    }
    if std::env::var_os(GATE).is_none() {
        println!("test m0::native_lifecycle ... ignored ({GATE} unset)");
        println!("test result: ok. 0 passed; 0 failed; 1 ignored");
        return;
    }
    let result = std::panic::catch_unwind(|| -> TestResult<()> {
        let mut fixture = Fixture::create()?;
        // A failed or killed child has no live owned client before DROP begins.
        let status = watchdog(
            Command::new(std::env::current_exe()?)
                .arg("--scenario")
                .arg(&fixture.name)
                .spawn()?,
            Duration::from_secs(30),
        );
        let cleanup = fixture.cleanup();
        status?
            .success()
            .then_some(())
            .ok_or("native scenario child failed")?;
        cleanup?;
        Ok(())
    });
    if let Ok(Err(error)) = &result {
        report_error(error.as_ref());
    }
    if !matches!(result, Ok(Ok(()))) || CLEANUP_FAILED.load(Ordering::SeqCst) {
        eprintln!("test result: FAILED (setup/scenario/cleanup failure; credentials redacted)");
        std::process::exit(1);
    }
    println!("test result: ok. M0 native lifecycle passed; 0 ignored");
}
