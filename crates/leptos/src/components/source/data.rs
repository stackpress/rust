//! Lossless Rust data port of Frui countries.ts and currencies.ts, in original array order.
//! Upstream files are read-only; source hashes identify the exact imported data.
use serde::Serialize;

/// One complete original country record; selector values use iso2, display lookup uses iso3.
#[derive(Clone, Debug, PartialEq, Serialize)]
pub struct CountryData {
    /// Original category.
    pub r#type: &'static str,
    /// Two-letter selector identity.
    pub iso2: &'static str,
    /// Three-letter view lookup identity.
    pub iso3: &'static str,
    /// Original display name.
    pub name: &'static str,
    /// Original flag emoji.
    pub flag: &'static str,
    /// Original northeast coordinates.
    pub ne: [f64; 2],
    /// Original southwest coordinates.
    pub sw: [f64; 2],
    /// Original currency code.
    pub cur: &'static str,
    /// Original dial prefix.
    pub tel: &'static str,
    /// Original language code.
    pub lang: &'static str,
    /// Original numeric separators.
    pub num: [&'static str; 2],
}
/// Complete original currency record, including non-fiat currencies and duplicates.
#[derive(Clone, Debug, PartialEq, Serialize)]
pub struct CurrencyData {
    /// Original category.
    pub r#type: &'static str,
    /// Original code.
    pub code: &'static str,
    /// Original display name.
    pub name: &'static str,
    /// Original plural spelling.
    pub plural: &'static str,
    /// Original symbol.
    pub symbol: &'static str,
}

