#!/usr/bin/env python3
"""Delete only the selected milestone's exact target and generated Profile asset outputs."""
import argparse
import json
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[3]


def main():
    """Refuse arbitrary targets and retain manifests/cleanup evidence for review."""
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--target',type=Path,required=True)
    parser.add_argument('--evidence',type=Path,required=True)
    parser.add_argument('--milestone',choices=['m1','m2'],default='m1')
    args=parser.parse_args()
    expected=ROOT/f'target/issue15-{args.milestone}'
    assert args.target.absolute()==expected and not args.target.is_symlink(), 'unexpected target'
    args.evidence.mkdir(parents=True,exist_ok=True)
    before=int(subprocess.check_output(['du','-sk',str(args.target)],text=True).split()[0]) if args.target.exists() else 0
    manifests=[]
    # Only the two outputs generated by this task's official build script are owned here.
    for mode in ['hydrate','csr']:
        output=ROOT/'examples/profile-ui/dist'/mode
        assert not output.is_symlink()
        manifest=output/'manifest.json'
        if manifest.exists():
            shutil.copyfile(manifest,args.evidence/f'profile-{mode}-manifest.json')
            manifests.append(mode)
        if output.exists():
            shutil.rmtree(output)
    if args.target.exists():
        shutil.rmtree(args.target)
    assert not args.target.exists()
    result={'target':str(args.target),'target_kib_before':before,'target_remaining':False,
            'profile_outputs_removed':manifests,'evidence_retained':str(args.evidence)}
    (args.evidence/'cleanup.json').write_text(json.dumps(result,indent=2)+'\n')
    print(json.dumps(result),flush=True)


if __name__ == '__main__':
    main()
